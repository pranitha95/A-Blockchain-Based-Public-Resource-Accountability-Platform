function buildDemoPdf(title: string, lines: string[]): Buffer {
  const escape = (value: string) => value.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
  const content = [
    'BT',
    '/F1 16 Tf',
    '72 744 Td',
    `(${escape(title)}) Tj`,
    '/F1 10 Tf',
    '0 -28 Td',
    ...lines.flatMap((line) => [`(${escape(line)}) Tj`, '0 -16 Td']),
    'ET',
  ].join('\n');

  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    `<< /Length ${Buffer.byteLength(content, 'latin1')} >>\nstream\n${content}\nendstream`,
  ];

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [];
  objects.forEach((body, index) => {
    offsets.push(Buffer.byteLength(pdf, 'latin1'));
    pdf += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xrefStart = Buffer.byteLength(pdf, 'latin1');
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    pdf += `${String(offset).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;
  return Buffer.from(pdf, 'latin1');
}

function sessionFor(row: DemoUserRow): SessionUser {
  return {
    id: row.id,
    email: row.email,
    fullName: row.full_name,
    role: row.role,
    status: 'ACTIVE',
    isDemo: true,
    capabilities: capabilitiesForRole(row.role),
  };
}

async function uploadDemoEvidence(
  actor: SessionUser,
  input: {
    projectId: string;
    title: string;
    description: string;
    visibility: EvidenceVisibility;
    milestoneId?: string | null;
    fileLabel: string;
    lines: string[];
  },
): Promise<{ id: string }> {
  const existing = await query<{ id: string }>(
    'SELECT id FROM evidence WHERE project_id = $1 AND title = $2 AND archived_at IS NULL LIMIT 1',
    [input.projectId, input.title],
  );
  if (existing.rows[0]) return { id: existing.rows[0].id };

  const file = buildDemoPdf(input.title, [
    'DEMONSTRATION EVIDENCE — not a real invoice or completion certificate.',
    ...input.lines,
    '',
    'This file was generated by the Proof of Impact demonstration seed.',
    'It must not be presented as genuine project evidence.',
  ]);
  const evidence = await uploadEvidence(
    actor,
    input.projectId,
    {
      title: input.title,
      description: input.description,
      visibility: input.visibility,
      milestoneId: input.milestoneId ?? null,
    },
    {
      buffer: file,
      originalname: `${input.fileLabel}.pdf`,
      size: file.length,
    },
  );
  return { id: evidence.id };
}

async function milestoneStatus(milestoneId: string): Promise<MilestoneStatus> {
  const result = await query<{ status: MilestoneStatus }>('SELECT status FROM milestones WHERE id = $1', [milestoneId]);
  if (!result.rows[0]) throw new Error(`Milestone ${milestoneId} was not found`);
  return result.rows[0].status;
}

async function ensureStarted(milestoneId: string, owner: SessionUser): Promise<void> {
  if (await milestoneStatus(milestoneId) === 'PLANNED') {
    await startMilestone(owner, milestoneId);
  }
}

async function ensureSubmission(
  owner: SessionUser,
  milestoneId: string,
  summary: string,
  evidenceId: string,
): Promise<{ submissionId: string; version: number }> {
  const existing = await query<{ id: string; version: number }>(
    'SELECT id, version FROM milestone_submissions WHERE milestone_id = $1 ORDER BY version DESC LIMIT 1',
    [milestoneId],
  );
  if (existing.rows[0]) {
    return { submissionId: existing.rows[0].id, version: Number(existing.rows[0].version) };
  }
  const detail = await submitMilestone(owner, milestoneId, { summary, evidenceIds: [evidenceId] });
  const latest = detail.latestSubmission;
  if (!latest) throw new Error('Milestone submission was not recorded');
  return { submissionId: latest.id, version: latest.version };
}

async function ensureMilestoneDecision(
  reviewer: SessionUser,
  submissionId: string,
  submissionVersion: number,
  decision: 'APPROVED' | 'REJECTED' | 'DISCREPANCY_OPENED',
  rationale: string,
): Promise<void> {
  const existing = await query(
    `SELECT 1 FROM reviews WHERE target_type = 'MILESTONE_SUBMISSION' AND target_id = $1 AND target_version = $2`,
    [submissionId, submissionVersion],
  );
  if ((existing.rowCount ?? 0) === 0) {
    await createReview(reviewer, 'MILESTONE_SUBMISSION', submissionId, { decision, rationale });
  }
}

async function ensureClaimReview(
  reviewer: SessionUser,
  claim: ClaimView,
  decision: 'APPROVED' | 'REJECTED' | 'DISCREPANCY_OPENED',
  rationale: string,
): Promise<void> {
  if (!['SUBMITTED', 'UNDER_REVIEW'].includes(claim.status)) return;
  const existing = await query(
    `SELECT 1 FROM reviews WHERE target_type = 'EXPENDITURE_CLAIM' AND target_id = $1 AND target_version = $2`,
    [claim.id, claim.version],
  );
  if ((existing.rowCount ?? 0) === 0) {
    await createReview(reviewer, 'EXPENDITURE_CLAIM', claim.id, { decision, rationale });
  }
}

async function ensureApproved(projectId: string, admin: SessionUser): Promise<void> {
  let status = (await getProjectDetail(admin, projectId)).status;
  if (status === 'DRAFT') {
    await changeProjectStatus(admin, projectId, { status: 'SUBMITTED', reason: 'Submitted for administrator review.' });
    status = 'SUBMITTED';
  }
  if (status === 'SUBMITTED') {
    await changeProjectStatus(admin, projectId, {
      status: 'APPROVED',
      reason: 'Milestones verified against the registered plan; approved for implementation.',
    });
    status = 'APPROVED';
  }
  if (!['APPROVED', 'IN_PROGRESS', 'UNDER_REVIEW', 'COMPLETED'].includes(status)) {
    throw new Error(`Project ${projectId} is in unexpected status ${status}; cannot resume seed`);
  }
}

